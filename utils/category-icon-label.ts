/** The localized-name key (`k.categories.icons.*`) of an icon the picker offers. */
export function getIconLabelKey(name: CategoryIconName): string {
  return ICON_LABEL_KEYS[name];
}

/**
 * The localized-name key for a stored bare Ionicon name (`"fast-food"`), e.g. for the category
 * form's Icon row. `-outline` / `-sharp` variants share the base icon's name; unmapped names (drawn
 * with the fallback glyph) and no icon return null.
 */
export function findIconLabelKey(name: string | null | undefined): string | null {
  if (!name) return null;
  const base = name.replace(/-(outline|sharp)$/, '');
  return Object.prototype.hasOwnProperty.call(ICON_LABEL_KEYS, base)
    ? ICON_LABEL_KEYS[base as CategoryIconName]
    : null;
}
